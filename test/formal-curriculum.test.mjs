test('approved 555 directory preserves exact names, allocation and production boundaries',()=>{
 const catalog=curriculumCatalog();
 assert.deepEqual(catalog.courses.map(c=>[c.id,c.title,c.words]),formalPlan.courses.map(c=>[c.id,c.title,c.words]));
 assert.deepEqual(catalog.units.map(u=>[u.id,u.title]),formalPlan.units.map(u=>[u.id,u.title]));
 assert.equal(catalog.planVersion,formalPlanVersion);
 assert.deepEqual(catalog.counts,{words:3000,units:87,courses:555,newLessons:544,integration:10,frameOnly:1});
 assert.equal(catalog.courses.some(c=>testCourseIds.has(c.id)),false);
 assert.equal(catalog.courses.every(c=>c.status==='planned'&&c.production.release==='unpublished'),true);
 assert.equal(catalog.testData.countsTowardFormal,false);
 assert.equal(catalog.testData.courses.length,6);
 for(const c of catalog.testData.sample.checks)assert.equal(c.answers,undefined);
 const invalid=structuredClone(formalPlan);invalid.words[0].review1=invalid.words[0].course;
 assert.throws(()=>validateFormalPlan(invalid),/首教之后/);
 const duplicate=structuredClone(formalPlan);duplicate.courses[1].words.push('apple');
 assert.throws(()=>validateFormalPlan(duplicate),/重复首教/);
});

test('test evidence and checkpoints survive but cannot affect formal progress or summary',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'snow-formal-'));
 const store=new LearningStore({directory:dir});
 t.after(()=>{store.close();fs.rmSync(dir,{recursive:true,force:true});});
 const c=new CurriculumStore(store);
 c.evidence=new CurriculumEvidence(c,{checks:runtimeChecks,words:sample.words,steps:sample.steps,version:curriculumVersion});
 c.selectLevel('owner',{level:1,revision:0});
 const course='B1.01-L01',step=sample.steps.find(s=>s.course===course).id;
 c.saveProgress('owner',{course,step,revision:0,version:curriculumVersion});
 for(const variant of ['a','b'])store.db.prepare('INSERT INTO curriculum_evidence VALUES(?,?,?,?,?,?,?,?,?,?)').run('old-'+variant,'owner','W-hello-'+variant,'hello',variant,'oral',store.now(),'hello',99,'b101-evidence-v1');
 store.db.prepare('INSERT INTO curriculum_abilities VALUES(?,?,?,?,?)').run('owner','B1.01','B2.01','preserved prior test evidence',store.now());
 store.db.prepare('INSERT INTO events VALUES(?,?,?,?,?,?,?)').run('old-test','owner',store.now(),course,'old','expose',JSON.stringify({words:['hello']}));
 store.db.prepare('INSERT INTO events VALUES(?,?,?,?,?,?,?)').run('old-test-finish','owner',store.now(),course,'old','finish','{}');
 store.db.prepare('INSERT INTO checkpoints VALUES(?,?,?,?,?)').run('owner',course,JSON.stringify({vocabulary:{seen:['hello']}}),store.now(),3);
 const state=c.state('owner');
 assert.equal(state.evidence.learnedWords,0);
 assert.deepEqual(state.evidence.completedCourses,[]);
 assert.deepEqual(state.progress,[]);
 assert.deepEqual(state.abilities,[]);
 assert.equal(state.testData.evidence.learnedWords,1);
 assert.equal(state.testData.progress[0].revision,1);
 assert.equal(state.testData.abilities.length,1);
 assert.equal(c.state('other').testData.evidence.learnedWords,0);
 const summary=store.summary('owner',{courses:[]},{excludeCourses:testCourseIds,explored:[{id:course,category:'见面与基础表达'}],completed:[course]});
 assert.equal(summary.words,0);assert.equal(summary.courses,0);assert.equal(summary.completedCourses,0);
 assert.equal(store.db.prepare('SELECT count(*) n FROM curriculum_evidence').get().n,2);
 assert.equal(store.db.prepare('SELECT count(*) n FROM checkpoints').get().n,1);
 assert.equal(store.db.prepare('SELECT count(*) n FROM events').get().n,2);
 assert.throws(()=>c.saveProgress('owner',{course:formalPlan.courses[0].id,step:'fake',revision:0,version:formalPlanVersion}),{status:409});
});
